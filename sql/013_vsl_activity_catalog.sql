-- ── 7. activity_name: CHECK → FK against the catalog ────────────────────
-- Adding a new activity type going forward is now a single INSERT into
-- vsl_activity_types (plus its properties), not a migration touching this
-- constraint and two separate JS files.
alter table public.vsl_activities drop constraint if exists vsl_activities_activity_name_chk;
alter table public.vsl_activities
  add constraint vsl_activities_activity_name_fkey
  foreign key (activity_name) references public.vsl_activity_types(name);
