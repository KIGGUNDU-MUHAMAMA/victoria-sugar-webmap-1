-- Migration: 013_vsl_activity_catalog.sql
-- Purpose: (1) Turn Completion into a real enum (0/20/50/75/100), replacing
--          the old free 0-100 numeric input; (2) promote "Area covered" out
--          of activity_properties jsonb into its own real column; (3) create
--          a data-driven activity catalog (vsl_activity_types /
--          vsl_activity_type_properties / vsl_activity_common_fields) so the
--          webmap's Log Activity form and the dashboard's Add/Edit Activity
--          forms both read the same 17 activities + their extra properties
--          from the database, instead of each hardcoding its own JS copy of
--          the list (which is what let them drift out of sync).
--
-- Applied directly against the live "victoriasugar" Supabase project
-- (knhgliyghacvkeeptsfl) via the Supabase MCP; recorded here so the sql/
-- folder stays a faithful history of the schema.

-- ── 1. Completion enum ──────────────────────────────────────────────────
-- Round the two existing rows that predate the enum to their nearest
-- allowed value, then enforce it going forward. NULL (no progress logged)
-- stays allowed.
update public.vsl_activities set completion_value = 20 where completion_value = 18;
update public.vsl_activities set completion_value = 20 where completion_value = 25;

alter table public.vsl_activities
  add constraint vsl_activities_completion_value_chk
  check (completion_value is null or completion_value = any (array[0,20,50,75,100]::numeric[]));

-- ── 2. Area covered — promote out of activity_properties jsonb ─────────
alter table public.vsl_activities add column if not exists area_covered_acres numeric;

update public.vsl_activities
set area_covered_acres = (activity_properties->>'area_covered_acres')::numeric
where activity_properties ? 'area_covered_acres' and area_covered_acres is null;

update public.vsl_activities
set activity_properties = activity_properties - 'area_covered_acres'
where activity_properties ? 'area_covered_acres';

comment on column public.vsl_activities.area_covered_acres is
  'Area (in acres) actually covered so far when an activity is logged at less than 100% completion. Null/irrelevant once completion_value = 100.';

-- ── 3. Activity catalog tables ──────────────────────────────────────────
create table if not exists public.vsl_activity_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.vsl_activity_type_properties (
  id bigint generated by default as identity primary key,
  activity_type_id bigint not null references public.vsl_activity_types(id) on delete cascade,
  key text not null,
  label text not null,
  data_type text not null check (data_type in ('text','number','date','select','textarea')),
  options jsonb,
  option_labels jsonb,
  show_when jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (activity_type_id, key)
);

create table if not exists public.vsl_activity_common_fields (
  id bigint generated by default as identity primary key,
  key text not null unique,
  label text not null,
  data_type text not null check (data_type in ('text','number','date','select','textarea')),
  options jsonb,
  option_labels jsonb,
  show_when jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_vsl_activity_type_properties_type_id on public.vsl_activity_type_properties(activity_type_id);

alter table public.vsl_activity_types enable row level security;
alter table public.vsl_activity_type_properties enable row level security;
alter table public.vsl_activity_common_fields enable row level security;

create policy "activity_types read all" on public.vsl_activity_types for select to authenticated using (true);
create policy "activity_types read anon" on public.vsl_activity_types for select to anon using (true);
create policy "activity_types write admin_surveyor" on public.vsl_activity_types for all to authenticated
  using (vsl_is_role('ADMIN') or vsl_is_role('SURVEYOR'))
  with check (vsl_is_role('ADMIN') or vsl_is_role('SURVEYOR'));

create policy "activity_type_properties read all" on public.vsl_activity_type_properties for select to authenticated using (true);
create policy "activity_type_properties read anon" on public.vsl_activity_type_properties for select to anon using (true);
create policy "activity_type_properties write admin_surveyor" on public.vsl_activity_type_properties for all to authenticated
  using (vsl_is_role('ADMIN') or vsl_is_role('SURVEYOR'))
  with check (vsl_is_role('ADMIN') or vsl_is_role('SURVEYOR'));

create policy "activity_common_fields read all" on public.vsl_activity_common_fields for select to authenticated using (true);
create policy "activity_common_fields read anon" on public.vsl_activity_common_fields for select to anon using (true);
create policy "activity_common_fields write admin_surveyor" on public.vsl_activity_common_fields for all to authenticated
  using (vsl_is_role('ADMIN') or vsl_is_role('SURVEYOR'))
  with check (vsl_is_role('ADMIN') or vsl_is_role('SURVEYOR'));

